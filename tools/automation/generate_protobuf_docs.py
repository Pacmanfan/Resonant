#!/usr/bin/env python3
"""Writes docs/reference/PROTOBUF_API.md from the resonant.v1 contract (REQ-CHAT-20261126-012).

    python3 tools/automation/generate_protobuf_docs.py [--descriptors FILE] [--check]

The reference is generated from the .proto files and their comments: never
edit the Markdown, edit the comments. --check exits 1 when the checked-in
file differs from what the contract generates (the Python suite runs it).
"""

from __future__ import annotations

import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "docs" / "reference" / "PROTOBUF_API.md"
sys.path.insert(0, str(ROOT / "python"))


def _anchor(full_name: str) -> str:
    return full_name.lower().replace(".", "")


def render(contract) -> str:
    lines = [
        "# Resonant automation API: protobuf reference (resonant.v1)",
        "",
        "Generated by `tools/automation/generate_protobuf_docs.py` from `proto/` and its comments",
        "(REQ-CHAT-20261126-012, ADR-000216). Do not edit: change the `.proto` comments and regenerate.",
        "Guides: [the gRPC client guide](GRPC_CLIENT_GUIDE.md),",
        "[Python automation](PYTHON_AUTOMATION.md), [events and jobs](EVENTS_AND_JOBS.md).",
        "",
        "Conventions: SI units (meters, radians, seconds, hertz, pascals; the unit is in the field name or",
        "comment); every request starts with a `RequestHeader` (session, request id, idempotency key,",
        "expected project revision, dry run) and every response with a `ResponseHeader`; a refused call",
        "carries a `resonant.v1.Error` (see [errors](#errors)).",
        "",
        "## Services",
        "",
    ]
    services = sorted(s for s in contract.services if s.startswith("resonant.v1."))
    for s in services:
        count = sum(1 for m in contract.methods.values() if m.service == s)
        lines.append(f"- [{s.split('.')[-1]}](#{_anchor(s.split('.')[-1])}) ({count} method{'s' if count != 1 else ''})")
    lines.append("")
    used = set()
    for s in services:
        lines += [f"## {s.split('.')[-1]}", ""]
        if contract.services[s]:
            lines += [contract.services[s], ""]
        lines += ["| Method | Request | Response | Description |", "|---|---|---|---|"]
        for m in sorted((m for m in contract.methods.values() if m.service == s), key=lambda m: m.short_name):
            response = ("stream " if m.server_streaming else "") + f"`{m.output_type.split('.')[-1]}`"
            lines.append(f"| `{m.short_name}` | `{m.input_type.split('.')[-1]}` | {response} | {m.comment.replace('|', '/')} |")
            used.update((m.input_type, m.output_type))
        lines.append("")
    lines += ["## Messages", ""]
    for name in sorted(n for n in contract.messages if n.startswith("resonant.v1.")):
        doc = contract.messages[name]
        lines += [f"### {name.split('resonant.v1.', 1)[1]}", ""]
        if doc.comment:
            lines += [doc.comment, ""]
        if doc.fields:
            lines += ["| Field | Type | Description |", "|---|---|---|"]
            for f in doc.fields:
                label = f"{f.label} " if f.label else ""
                type_name = f.type_name.split("resonant.v1.", 1)[-1]
                lines.append(f"| `{f.name}` | {label}`{type_name}` | {f.comment.replace('|', '/')} |")
            lines.append("")
    lines += ["## Enums", ""]
    for file_proto in contract.file_set.file:
        if file_proto.package != "resonant.v1":
            continue
        for enum in file_proto.enum_type:
            lines += [f"### {enum.name}", "", ", ".join(f"`{v.name}` = {v.number}" for v in enum.value), ""]
    lines += [
        "## Errors",
        "",
        "A refused call ends with a gRPC status and a `resonant.v1.Error` (over gRPC in the trailing metadata",
        "`resonant-error-bin`): `INVALID_ARGUMENT` (3, with field violations), `NOT_FOUND` (5), `ALREADY_EXISTS` (6,",
        "also an idempotency key reused for another operation), `PERMISSION_DENIED` (7), `RESOURCE_EXHAUSTED` (8,",
        "e.g. a field too large to compute or read at once), `FAILED_PRECONDITION` (9), `CONFLICT` as `ABORTED` (10,",
        "with `current_revision`), `UNIMPLEMENTED` (12), `INTERNAL` (13), `UNAVAILABLE` (14, retryable),",
        "`CANCELLED` (1); `UNAUTHENTICATED` (16) when the token is missing or wrong.",
        "",
    ]
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--descriptors", help="a descriptor set (default: compile proto/ with protoc)")
    parser.add_argument("--check", action="store_true", help="fail when the checked-in reference is out of date")
    args = parser.parse_args(argv)
    from resonant_api.contract import Contract, compile_descriptor_set

    data = pathlib.Path(args.descriptors).read_bytes() if args.descriptors else compile_descriptor_set(ROOT / "proto")
    text = render(Contract(data))
    if args.check:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date: run tools/automation/generate_protobuf_docs.py")
            return 1
        print("protobuf docs: up to date")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
